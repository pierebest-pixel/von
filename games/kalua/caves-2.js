async function bell(D, which) {
  const want = ["grave", "aigue", "moyenne"]; D.R.bseq = D.R.bseq || [];
  Music.sfx("bell", which === "grave" ? 1 : .5);
  D.R.bseq.push(which); const i = D.R.bseq.length - 1;
  if (D.R.bseq[i] !== want[i]) { D.R.bseq = []; D.toast("Les cloches sonnent faux… Recommence."); return; }
  D.toast(`🔔 ${i + 1}/3`); if (D.R.bseq.length === 3) D.R.bells = 3;
}
